'use client'

import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card'
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs'
import { Badge } from '@/components/ui/badge'
import { Progress } from '@/components/ui/progress'
import { Separator } from '@/components/ui/separator'
import {
  BarChart,
  Bar,
  XAxis,
  YAxis,
  Tooltip,
  ResponsiveContainer,
  PieChart,
  Pie,
  Cell,
  CartesianGrid,
  Legend,
} from 'recharts'
import type { AnalysisResult } from '@/lib/exam-analyzer'
import {
  LayoutDashboard,
  Tags,
  PieChart as PieIcon,
  Gauge,
  Repeat,
  Lightbulb,
  AlertTriangle,
  Target,
  BookOpenCheck,
  Clock,
  Hash,
  TrendingUp,
} from 'lucide-react'

type Props = { result: AnalysisResult }

const CHART_COLORS = ['#0d9488', '#f59e0b', '#8b5cf6', '#ef4444', '#0ea5e9', '#ec4899', '#84cc16', '#f97316']

const DIFFICULTY_COLOR: Record<string, string> = {
  Easy: '#10b981',
  Medium: '#f59e0b',
  Hard: '#ef4444',
}

export function ResultsDashboard({ result }: Props) {
  return (
    <div className="space-y-6">
      {/* Headline summary card */}
      <Card className="border-2 border-emerald-900/15 bg-gradient-to-br from-emerald-50/50 to-amber-50/30 dark:from-emerald-950/20 dark:to-amber-950/10">
        <CardHeader>
          <div className="flex items-start justify-between gap-4 flex-wrap">
            <div className="flex-1 min-w-[280px]">
              <CardTitle className="text-2xl flex items-center gap-2">
                <LayoutDashboard className="size-6 text-emerald-700 dark:text-emerald-400" />
                Analysis Summary
              </CardTitle>
              <CardDescription className="mt-1">Generated by {result.rawModelLabel}</CardDescription>
            </div>
            <div className="grid grid-cols-3 gap-3">
              <StatBadge icon={<Hash className="size-3.5" />} label="Questions" value={String(result.totalQuestions)} />
              <StatBadge icon={<Clock className="size-3.5" />} label="Duration" value={result.estimatedDuration} />
              <StatBadge icon={<BookOpenCheck className="size-3.5" />} label="Total marks" value={String(result.totalMarks)} />
            </div>
          </div>
        </CardHeader>
        <CardContent>
          <p className="text-sm leading-relaxed text-foreground/90">{result.summary}</p>
        </CardContent>
      </Card>

      <Tabs defaultValue="topics" className="w-full">
        <TabsList className="grid w-full grid-cols-3 sm:grid-cols-6 h-auto">
          <TabsTrigger value="topics" className="gap-1 text-xs sm:text-sm"><Tags className="size-3.5" />Topics</TabsTrigger>
          <TabsTrigger value="types" className="gap-1 text-xs sm:text-sm"><PieIcon className="size-3.5" />Types</TabsTrigger>
          <TabsTrigger value="difficulty" className="gap-1 text-xs sm:text-sm"><Gauge className="size-3.5" />Difficulty</TabsTrigger>
          <TabsTrigger value="patterns" className="gap-1 text-xs sm:text-sm"><Repeat className="size-3.5" />Patterns</TabsTrigger>
          <TabsTrigger value="predictions" className="gap-1 text-xs sm:text-sm"><Target className="size-3.5" />Predict</TabsTrigger>
          <TabsTrigger value="strategy" className="gap-1 text-xs sm:text-sm"><Lightbulb className="size-3.5" />Strategy</TabsTrigger>
        </TabsList>

        {/* TOPICS TAB */}
        <TabsContent value="topics" className="mt-4">
          <Card>
            <CardHeader>
              <CardTitle className="flex items-center gap-2 text-lg">
                <Tags className="size-5 text-emerald-700 dark:text-emerald-400" />
                Topic Distribution
              </CardTitle>
              <CardDescription>How many questions touch each subject area, with the engine&apos;s difficulty rating.</CardDescription>
            </CardHeader>
            <CardContent>
              {result.topics.length === 0 ? (
                <EmptyState label="No topics were extracted." />
              ) : (
                <div className="grid lg:grid-cols-2 gap-6">
                  <div className="h-[320px]">
                    <ResponsiveContainer width="100%" height="100%">
                      <BarChart data={result.topics} layout="vertical" margin={{ left: 20, right: 20, top: 10, bottom: 10 }}>
                        <CartesianGrid strokeDasharray="3 3" opacity={0.25} horizontal={false} />
                        <XAxis type="number" tick={{ fontSize: 12 }} domain={[0, 100]} unit="%" />
                        <YAxis dataKey="topic" type="category" width={120} tick={{ fontSize: 11 }} interval={0} />
                        <Tooltip
                          formatter={(v: number) => [`${v}%`, 'Share']}
                          contentStyle={{ borderRadius: 8, fontSize: 12 }}
                        />
                        <Bar dataKey="percentage" radius={[0, 4, 4, 0]}>
                          {result.topics.map((_, i) => (
                            <Cell key={i} fill={CHART_COLORS[i % CHART_COLORS.length]} />
                          ))}
                        </Bar>
                      </BarChart>
                    </ResponsiveContainer>
                  </div>
                  <div className="space-y-2">
                    {result.topics.map((t, i) => (
                      <div key={i} className="space-y-1 p-3 rounded-lg border bg-card">
                        <div className="flex items-center justify-between">
                          <span className="text-sm font-medium">{t.topic}</span>
                          <Badge variant="outline" style={{ color: DIFFICULTY_COLOR[t.difficulty] }}>
                            {t.difficulty}
                          </Badge>
                        </div>
                        <div className="flex items-center gap-2 text-xs text-muted-foreground">
                          <span>{t.count} questions</span>
                          <span>•</span>
                          <span>{t.percentage}%</span>
                        </div>
                        <Progress value={t.percentage} className="h-1.5" />
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </CardContent>
          </Card>
        </TabsContent>

        {/* QUESTION TYPES TAB */}
        <TabsContent value="types" className="mt-4">
          <Card>
            <CardHeader>
              <CardTitle className="flex items-center gap-2 text-lg">
                <PieIcon className="size-5 text-amber-600 dark:text-amber-400" />
                Question Type Breakdown
              </CardTitle>
              <CardDescription>How the exam is structured by format (MCQ, short answer, essay, etc.).</CardDescription>
            </CardHeader>
            <CardContent>
              {result.questionTypes.length === 0 ? (
                <EmptyState label="No question types were extracted." />
              ) : (
                <div className="grid lg:grid-cols-2 gap-6">
                  <div className="h-[300px]">
                    <ResponsiveContainer width="100%" height="100%">
                      <PieChart>
                        <Pie
                          data={result.questionTypes}
                          dataKey="percentage"
                          nameKey="type"
                          cx="50%"
                          cy="50%"
                          outerRadius={90}
                          label={(entry) => `${entry.type} ${entry.percentage}%`}
                          labelLine={false}
                        >
                          {result.questionTypes.map((_, i) => (
                            <Cell key={i} fill={CHART_COLORS[i % CHART_COLORS.length]} />
                          ))}
                        </Pie>
                        <Tooltip formatter={(v: number) => [`${v}%`, 'Share']} contentStyle={{ borderRadius: 8, fontSize: 12 }} />
                      </PieChart>
                    </ResponsiveContainer>
                  </div>
                  <div className="space-y-2">
                    {result.questionTypes.map((q, i) => (
                      <div key={i} className="p-3 rounded-lg border bg-card space-y-1">
                        <div className="flex items-center justify-between">
                          <div className="flex items-center gap-2">
                            <span
                              className="inline-block size-3 rounded-sm"
                              style={{ background: CHART_COLORS[i % CHART_COLORS.length] }}
                            />
                            <span className="text-sm font-medium">{q.type}</span>
                          </div>
                          <span className="text-sm text-muted-foreground">
                            {q.count} ({q.percentage}%)
                          </span>
                        </div>
                        <p className="text-xs text-muted-foreground">{q.notes}</p>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </CardContent>
          </Card>
        </TabsContent>

        {/* DIFFICULTY TAB */}
        <TabsContent value="difficulty" className="mt-4">
          <Card>
            <CardHeader>
              <CardTitle className="flex items-center gap-2 text-lg">
                <Gauge className="size-5 text-rose-600 dark:text-rose-400" />
                Difficulty Distribution
              </CardTitle>
              <CardDescription>How the exam is weighted across easy, medium, and hard questions.</CardDescription>
            </CardHeader>
            <CardContent>
              {result.difficulty.length === 0 ? (
                <EmptyState label="No difficulty data was extracted." />
              ) : (
                <div className="space-y-6">
                  <div className="h-[280px]">
                    <ResponsiveContainer width="100%" height="100%">
                      <BarChart data={result.difficulty} margin={{ top: 10, right: 20, bottom: 10, left: 0 }}>
                        <CartesianGrid strokeDasharray="3 3" opacity={0.25} />
                        <XAxis dataKey="level" tick={{ fontSize: 12 }} />
                        <YAxis tick={{ fontSize: 12 }} unit="%" domain={[0, 100]} />
                        <Tooltip
                          formatter={(v: number) => [`${v}%`, 'Share']}
                          contentStyle={{ borderRadius: 8, fontSize: 12 }}
                        />
                        <Bar dataKey="percentage" radius={[6, 6, 0, 0]}>
                          {result.difficulty.map((d, i) => (
                            <Cell key={i} fill={DIFFICULTY_COLOR[d.level] ?? '#999'} />
                          ))}
                        </Bar>
                      </BarChart>
                    </ResponsiveContainer>
                  </div>
                  <div className="grid sm:grid-cols-3 gap-3">
                    {result.difficulty.map((d, i) => (
                      <div
                        key={i}
                        className="p-4 rounded-lg border bg-card space-y-1.5"
                        style={{ borderLeft: `4px solid ${DIFFICULTY_COLOR[d.level] ?? '#999'}` }}
                      >
                        <div className="flex items-center justify-between">
                          <span className="text-sm font-semibold">{d.level}</span>
                          <span className="text-sm text-muted-foreground">
                            {d.count} Q ({d.percentage}%)
                          </span>
                        </div>
                        <p className="text-xs text-muted-foreground">{d.example}</p>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </CardContent>
          </Card>
        </TabsContent>

        {/* RECURRING PATTERNS TAB */}
        <TabsContent value="patterns" className="mt-4">
          <Card>
            <CardHeader>
              <CardTitle className="flex items-center gap-2 text-lg">
                <Repeat className="size-5 text-violet-600 dark:text-violet-400" />
                Recurring Patterns
              </CardTitle>
              <CardDescription>
                Structural and content patterns the engine has seen repeat across the exam — with strategy recommendations.
              </CardDescription>
            </CardHeader>
            <CardContent>
              {result.recurringPatterns.length === 0 ? (
                <EmptyState label="No recurring patterns were detected." />
              ) : (
                <div className="grid md:grid-cols-2 gap-4">
                  {result.recurringPatterns.map((p, i) => (
                    <div
                      key={i}
                      className="p-4 rounded-lg border bg-card space-y-2 hover:shadow-md transition-shadow"
                    >
                      <div className="flex items-start justify-between gap-2">
                        <h4 className="font-semibold text-sm flex items-center gap-1">
                          <TrendingUp className="size-4 text-violet-600 dark:text-violet-400" />
                          {p.title}
                        </h4>
                        <Badge variant="secondary" className="text-xs">
                          ×{p.frequency}
                        </Badge>
                      </div>
                      <p className="text-sm text-muted-foreground">{p.description}</p>
                      <Separator />
                      <div className="space-y-1 text-xs">
                        <p>
                          <span className="font-medium text-foreground">Evidence:</span>{' '}
                          <span className="text-muted-foreground">{p.evidence}</span>
                        </p>
                        <p>
                          <span className="font-medium text-foreground">Strategy:</span>{' '}
                          <span className="text-muted-foreground">{p.strategy}</span>
                        </p>
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </CardContent>
          </Card>
        </TabsContent>

        {/* PREDICTIONS TAB */}
        <TabsContent value="predictions" className="mt-4">
          <Card>
            <CardHeader>
              <CardTitle className="flex items-center gap-2 text-lg">
                <Target className="size-5 text-emerald-700 dark:text-emerald-400" />
                Predicted Focus
              </CardTitle>
              <CardDescription>
                Topics the engine believes are most likely to appear in a future paper based on the patterns observed.
              </CardDescription>
            </CardHeader>
            <CardContent>
              {result.predictedFocus.length === 0 ? (
                <EmptyState label="No predictions were generated." />
              ) : (
                <div className="space-y-3">
                  {result.predictedFocus.map((p, i) => (
                    <div key={i} className="p-4 rounded-lg border bg-card space-y-2">
                      <div className="flex items-center justify-between gap-3">
                        <span className="text-sm font-medium">{p.topic}</span>
                        <Badge
                          variant="outline"
                          className={
                            p.likelihood >= 70
                              ? 'border-emerald-600 text-emerald-700 dark:text-emerald-400'
                              : p.likelihood >= 40
                              ? 'border-amber-500 text-amber-700 dark:text-amber-400'
                              : 'border-muted-foreground text-muted-foreground'
                          }
                        >
                          {p.likelihood}% likely
                        </Badge>
                      </div>
                      <Progress
                        value={p.likelihood}
                        className="h-2"
                        style={
                          {
                            background: 'rgba(0,0,0,0.05)',
                          } as React.CSSProperties
                        }
                      />
                      <p className="text-xs text-muted-foreground">{p.reasoning}</p>
                    </div>
                  ))}
                </div>
              )}
            </CardContent>
          </Card>
        </TabsContent>

        {/* STRATEGY TAB */}
        <TabsContent value="strategy" className="mt-4">
          <div className="grid lg:grid-cols-3 gap-4">
            <Card className="lg:col-span-2">
              <CardHeader>
                <CardTitle className="flex items-center gap-2 text-lg">
                  <Lightbulb className="size-5 text-amber-600 dark:text-amber-400" />
                  Study Strategy
                </CardTitle>
                <CardDescription>Concrete, prioritised actions to prepare based on the patterns above.</CardDescription>
              </CardHeader>
              <CardContent>
                {result.studyStrategy.length === 0 ? (
                  <EmptyState label="No strategy was generated." />
                ) : (
                  <ol className="space-y-2 list-none">
                    {result.studyStrategy.map((s, i) => (
                      <li key={i} className="flex gap-3 p-3 rounded-lg border bg-card">
                        <span className="flex-shrink-0 size-6 rounded-full bg-emerald-700 text-white text-xs font-semibold flex items-center justify-center">
                          {i + 1}
                        </span>
                        <span className="text-sm leading-relaxed">{s}</span>
                      </li>
                    ))}
                  </ol>
                )}
              </CardContent>
            </Card>

            <Card className="border-rose-300/50 dark:border-rose-900/40">
              <CardHeader>
                <CardTitle className="flex items-center gap-2 text-lg text-rose-700 dark:text-rose-400">
                  <AlertTriangle className="size-5" />
                  Red Flags
                </CardTitle>
                <CardDescription>Risky or unfair patterns students should be aware of.</CardDescription>
              </CardHeader>
              <CardContent>
                {result.redFlags.length === 0 ? (
                  <EmptyState label="No red flags detected." />
                ) : (
                  <ul className="space-y-2">
                    {result.redFlags.map((r, i) => (
                      <li key={i} className="flex gap-2 text-sm">
                        <AlertTriangle className="size-4 mt-0.5 text-rose-600 dark:text-rose-400 flex-shrink-0" />
                        <span className="leading-relaxed">{r}</span>
                      </li>
                    ))}
                  </ul>
                )}
              </CardContent>
            </Card>
          </div>

          {/* Cognitive levels sub-section */}
          {result.cognitiveLevels.length > 0 && (
            <Card className="mt-4">
              <CardHeader>
                <CardTitle className="text-lg flex items-center gap-2">
                  <Gauge className="size-5 text-sky-700 dark:text-sky-400" />
                  Cognitive Levels (Bloom&apos;s)
                </CardTitle>
                <CardDescription>How the exam tests different levels of thinking.</CardDescription>
              </CardHeader>
              <CardContent>
                <div className="h-[260px]">
                  <ResponsiveContainer width="100%" height="100%">
                    <BarChart data={result.cognitiveLevels} margin={{ top: 10, right: 20, bottom: 10, left: 0 }}>
                      <CartesianGrid strokeDasharray="3 3" opacity={0.25} />
                      <XAxis dataKey="level" tick={{ fontSize: 11 }} />
                      <YAxis tick={{ fontSize: 12 }} unit="%" domain={[0, 100]} />
                      <Tooltip formatter={(v: number) => [`${v}%`, 'Share']} contentStyle={{ borderRadius: 8, fontSize: 12 }} />
                      <Legend />
                      <Bar dataKey="percentage" radius={[6, 6, 0, 0]} fill="#0ea5e9" />
                    </BarChart>
                  </ResponsiveContainer>
                </div>
              </CardContent>
            </Card>
          )}
        </TabsContent>
      </Tabs>
    </div>
  )
}

function StatBadge({ icon, label, value }: { icon: React.ReactNode; label: string; value: string }) {
  return (
    <div className="flex flex-col items-center justify-center px-3 py-2 rounded-lg border bg-background/80 min-w-[80px]">
      <div className="flex items-center gap-1 text-xs text-muted-foreground mb-0.5">
        {icon}
        <span>{label}</span>
      </div>
      <span className="text-base font-semibold">{value}</span>
    </div>
  )
}

function EmptyState({ label }: { label: string }) {
  return (
    <div className="py-10 text-center text-sm text-muted-foreground border border-dashed rounded-lg">{label}</div>
  )
}
